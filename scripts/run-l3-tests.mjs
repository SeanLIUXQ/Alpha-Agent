const registry = await createDefaultSkillRegistry();

async function readSandboxContext(filePaths) {
  const files = [];

  for (const filePath of filePaths) {
    try {
      files.push({
        path: filePath,
        reason: 'L3 regression fixture from Conduit sandbox',
        content: await readFile(path.resolve('apps/conduit-sandbox', filePath), 'utf8')
      });
    } catch {
      // New files such as migrations are generated by CodeAgent and do not need existing content.
    }
  }

  return {
    files,
    constraints: ['L3 regression test context'],
    searchedTerms: []
  };
}

